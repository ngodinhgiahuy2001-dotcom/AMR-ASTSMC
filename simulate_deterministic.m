function result = simulate_deterministic(p,controller,caseNo)

%% Time vector

dt = p.sim.dt;

t = (p.sim.t0:dt:p.sim.tf)';

N = numel(t);


%% Initial reference

r0 = model_reference_trajectory( ...
    t(1), ...
    p);


q0 = ...
    r0(1:3) ...
    + p.init.dq;


eta0 = ...
    r0(4:5) ...
    + p.init.deta;


%% Initial states

switch upper(controller)

    case 'SMC'

        x0 = [ ...
            q0; ...
            eta0];


    case 'STSMC'

        x0 = [ ...
            q0; ...
            eta0; ...
            0; ...
            0];


    case 'ASTSMC'

        x0 = [ ...
            q0; ...
            eta0; ...
            0; ...
            0; ...
            p.AST.alpha0];


    otherwise

        error( ...
            'Unknown controller: %s', ...
            controller);

end


%% Allocate

nx = numel(x0);

x = zeros(N,nx);

x(1,:) = x0.';


%% =========================================================
%  Fixed-step RK4
% ==========================================================

for k = 1:N-1

    tk = t(k);

    xk = x(k,:).';


    k1 = model_robot_dynamics( ...
        tk, ...
        xk, ...
        p, ...
        controller, ...
        caseNo);


    k2 = model_robot_dynamics( ...
        tk + dt/2, ...
        xk + dt*k1/2, ...
        p, ...
        controller, ...
        caseNo);


    k3 = model_robot_dynamics( ...
        tk + dt/2, ...
        xk + dt*k2/2, ...
        p, ...
        controller, ...
        caseNo);


    k4 = model_robot_dynamics( ...
        tk + dt, ...
        xk + dt*k3, ...
        p, ...
        controller, ...
        caseNo);


    xNext = ...
        xk ...
        + dt/6 * ( ...
            k1 ...
            + 2*k2 ...
            + 2*k3 ...
            + k4);


    %% ASTSMC projection

    if strcmpi(controller,'ASTSMC')

        xNext(8:9) = ...
            max( ...
                xNext(8:9), ...
                p.AST.alphaMin);


        xNext(8:9) = ...
            min( ...
                xNext(8:9), ...
                p.AST.alphaMax);

    end


    %% Heading wrap

    xNext(3) = ...
        atan2( ...
            sin(xNext(3)), ...
            cos(xNext(3)));


    x(k+1,:) = xNext.';

end


%% =========================================================
%  POST PROCESS
% ==========================================================

result = compute_metrics( ...
    t, ...
    x, ...
    p, ...
    controller, ...
    caseNo);

end



