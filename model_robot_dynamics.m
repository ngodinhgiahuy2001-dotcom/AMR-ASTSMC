function dx = model_robot_dynamics(t,x,p,controller,caseNo)

%% States
q   = x(1:3);
eta = x(4:5);

v = eta(1);
w = eta(2);


%% Reference
r = model_reference_trajectory(t,p);

xd   = r(1);
yd   = r(2);
thd  = r(3);
vd   = r(4);
wd   = r(5);
dvd  = r(6);
dwd  = r(7);


%% Body-frame pose errors
Dx = xd - q(1);
Dy = yd - q(2);

th = q(3);

ex = ...
    cos(th)*Dx ...
    + sin(th)*Dy;

ey = ...
    -sin(th)*Dx ...
    + cos(th)*Dy;

eth = atan2( ...
    sin(thd-th), ...
    cos(thd-th));


%% Outer-loop velocity commands
vc = ...
    vd*cos(eth) ...
    + p.outer.kx*ex;

wc = ...
    wd ...
    + p.outer.ky*vd*ey ...
    + p.outer.kth*sin(eth);


%% Pose-error derivatives
exd = ...
    w*ey ...
    - v ...
    + vd*cos(eth);

eyd = ...
    -w*ex ...
    + vd*sin(eth);

ethd = ...
    wd ...
    - w;


%% Command derivatives
vcd = ...
    dvd*cos(eth) ...
    - vd*sin(eth)*ethd ...
    + p.outer.kx*exd;

wcd = ...
    dwd ...
    + p.outer.ky*( ...
        dvd*ey ...
        + vd*eyd) ...
    + p.outer.kth*cos(eth)*ethd;


%% Sliding variables
s = [ ...
    v-vc; ...
    w-wc];


%% Robust controller
switch upper(controller)

    case 'SMC'

        nu = controller_SMC(s,p);

        zdot = [];
        alphadot = [];


    case 'STSMC'

        z = x(6:7);

        [nu,zdot] = ...
            controller_STSMC( ...
                s, ...
                z, ...
                p);

        alphadot = [];


    case 'ASTSMC'

        z     = x(6:7);
        alpha = x(8:9);

        [nu,zdot,alphadot] = ...
            controller_ASTSMC( ...
                s, ...
                z, ...
                alpha, ...
                p);


    otherwise

        error('Unknown controller: %s',controller);

end


%% Generalized control inputs
uv = ...
    p.Bv0*v ...
    + p.m0*vcd ...
    + p.m0*nu(1);

uw = ...
    p.Bw0*w ...
    + p.J0*wcd ...
    + p.J0*nu(2);


%% Lumped uncertainty
phi = [0;0];

switch caseNo

    case 1

        phi = [0;0];


    case 2

        phi = model_external_disturbance(t,p);


    case 3

        % Combined scenario: same external model_external_disturbance as Case 2
        % plus equivalent acceleration model_external_disturbance from variable payload.
        phi = model_external_disturbance(t,p) + payload_uncertainty( ...
            t, ...
            v, ...
            r, ...
            p);


    otherwise

        error('Unknown case number.');

end


%% Velocity model_robot_dynamics
vdot = ...
    -p.Bv0/p.m0*v ...
    + uv/p.m0 ...
    + phi(1);

wdot = ...
    -p.Bw0/p.J0*w ...
    + uw/p.J0 ...
    + phi(2);

etadot = [vdot;wdot];


%% Kinematics
qdot = model_robot_kinematics(q,eta);


%% Full state derivative
switch upper(controller)

    case 'SMC'

        dx = [ ...
            qdot; ...
            etadot];


    case 'STSMC'

        dx = [ ...
            qdot; ...
            etadot; ...
            zdot];


    case 'ASTSMC'

        dx = [ ...
            qdot; ...
            etadot; ...
            zdot; ...
            alphadot];

end

end


function phi = payload_uncertainty(t,v,r,p)

mp = model_payload_profile(t);

if mp <= 0

    phi = [0;0];
    return;

end


ratio = mp/p.mp_max;

dvd = r(6);
dwd = r(7);


%% Longitudinal equivalent residual
F_in = ...
    -p.payload.k_in_v ...
    * mp ...
    * dvd;

F_fr = ...
    -p.payload.c_rr ...
    * mp ...
    * p.g ...
    * tanh(v/0.12);

F_osc = ...
    p.payload.Fosc ...
    * ratio ...
    * sin(2.2*t + 0.3);

Fres = ...
    F_in ...
    + F_fr ...
    + F_osc;


%% Yaw equivalent residual
dJ = ...
    p.payload.kJ ...
    * mp ...
    * p.payload.r_eff^2;

M_in = ...
    -p.payload.k_in_w ...
    * dJ ...
    * dwd;

M_off = ...
    -p.payload.y_off ...
    * F_in;

M_osc = ...
    p.payload.Mosc ...
    * ratio ...
    * sin(1.7*t + 0.8);

Mres = ...
    M_in ...
    + M_off ...
    + M_osc;


%% Acceleration-level lumped uncertainty
phi = [ ...
    Fres/p.m0; ...
    Mres/p.J0];

end